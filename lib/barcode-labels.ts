export function chooseLabelSize(productName: string, color: string, quantity: string, unit: string): string {
  const score = productName.trim().length + color.trim().length + (quantity ? 8 : 0) + (unit ? 8 : 0);
  if (!productName.trim() && !color.trim()) return "25x15";
  if (score <= 18) return "40x25";
  if (score <= 28) return "50x25";
  if (score <= 42) return "50x30";
  if (score <= 58) return "50x40";
  if (score <= 78) return "60x40";
  if (score <= 110) return "70x50";
  return "100x50";
}

